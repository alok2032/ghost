#!/usr/bin/env bash
# Auto-generates docs/FACTS.md from authoritative code & config files.
# Usage:
#   bash scripts/gen-facts.sh          -> writes docs/FACTS.md
#   bash scripts/gen-facts.sh --check  -> exits 1 if docs/FACTS.md is stale
set -euo pipefail
cd "$(dirname "$0")/.."

OUT="docs/FACTS.md"
TMP="$(mktemp)"
trap 'rm -f "$TMP"' EXIT

APP_ID=$(grep -o 'applicationId *= *"[^"]*"' app/build.gradle.kts | head -1 | sed 's/.*= *"//;s/"//')
MIN_SDK=$(grep -o 'minSdk *= *[0-9]*' app/build.gradle.kts | head -1 | sed 's/.*= *//')
TARGET_SDK=$(grep -o 'targetSdk *= *[0-9]*' app/build.gradle.kts | head -1 | sed 's/.*= *//')
COMPILE_SDK=$(grep -o 'compileSdk *= *[0-9]*' app/build.gradle.kts | head -1 | sed 's/.*= *//')
ROOM_VER=$(grep -oE 'version\s*=\s*[0-9]+' app/src/main/java/com/ayra/ai/app/data/ChatDatabase.kt | head -1 | sed 's/.*= *//')
EXPORT_SCHEMA=$(grep -oE 'exportSchema\s*=\s*(true|false)' app/src/main/java/com/ayra/ai/app/data/ChatDatabase.kt | head -1 | sed 's/.*= *//')
GS_PKG=$(grep -o '"package_name": *"[^"]*"' app/google-services.json 2>/dev/null | head -1 | sed 's/.*: *"//;s/"//' || echo "missing")

KT_MAIN_COUNT=$(find app/src/main -name '*.kt' | wc -l | tr -d ' ')
KT_TEST_COUNT=$(find app/src/test -name '*.kt' | wc -l | tr -d ' ')
AT_TEST_COUNT=$(grep -rn '@Test' app/src/test 2>/dev/null | wc -l | tr -d ' ')
SWALLOWED_COUNT=$(grep -rnE 'catch\s*\(\s*_\s*:\s*(Exception|Throwable)' app/src/main 2>/dev/null | wc -l | tr -d ' ')
BACKEND_TEST_COUNT=$(grep -rnE '^test\(' backend/test/ 2>/dev/null | wc -l | tr -d ' ')
RULES_TEST_COUNT=$(grep -rnE '(it|test)\(' firestore.test.js 2>/dev/null | wc -l | tr -d ' ')

KOTLIN_VER=$(grep -E '^kotlin\s*=' gradle/libs.versions.toml | head -1 | sed 's/.*= *"//;s/"//')
AGP_VER=$(grep -E '^agp\s*=' gradle/libs.versions.toml | head -1 | sed 's/.*= *"//;s/"//')
COMPOSE_BOM=$(grep -E '^composeBom\s*=' gradle/libs.versions.toml | head -1 | sed 's/.*= *"//;s/"//')
FIREBASE_BOM=$(grep -E '^firebaseBom\s*=' gradle/libs.versions.toml | head -1 | sed 's/.*= *"//;s/"//')
OKHTTP_VER=$(grep -E '^okhttp\s*=' gradle/libs.versions.toml | head -1 | sed 's/.*= *"//;s/"//')
ROOM_LIB_VER=$(grep -E '^roomRuntime\s*=' gradle/libs.versions.toml | head -1 | sed 's/.*= *"//;s/"//')
SQLCIPHER_VER=$(grep -E '^sqlcipher\s*=' gradle/libs.versions.toml | head -1 | sed 's/.*= *"//;s/"//')

cat > "$TMP" <<EOF
# AYRA AI — Generated Ground-Truth Facts

> Auto-generated by \`scripts/gen-facts.sh\`. Never edit manually or copy Firebase project IDs / SHAs / counts by hand into other markdown docs.

| Metric / Config | Verified Value | Source File |
|---|---|---|
| Application ID | \`$APP_ID\` | \`app/build.gradle.kts\` |
| Google Services Package | \`$GS_PKG\` | \`app/google-services.json\` |
| Compile / Target / Min SDK | \`$COMPILE_SDK\` / \`$TARGET_SDK\` / \`$MIN_SDK\` | \`app/build.gradle.kts\` |
| Room Schema Version / \`exportSchema\` | \`v$ROOM_VER\` / \`$EXPORT_SCHEMA\` | \`ChatDatabase.kt\` |
| Kotlin / AGP | \`$KOTLIN_VER\` / \`$AGP_VER\` | \`gradle/libs.versions.toml\` |
| Compose BOM / Firebase BOM | \`$COMPOSE_BOM\` / \`$FIREBASE_BOM\` | \`gradle/libs.versions.toml\` |
| Room / SQLCipher / OkHttp | \`$ROOM_LIB_VER\` / \`$SQLCIPHER_VER\` / \`$OKHTTP_VER\` | \`gradle/libs.versions.toml\` |
| Kotlin Main Source Files | \`$KT_MAIN_COUNT\` | \`app/src/main\` |
| Android Unit Test Files / \`@Test\` Cases | \`$KT_TEST_COUNT\` files / \`$AT_TEST_COUNT\` tests | \`app/src/test\` |
| Backend Node Tests | \`$BACKEND_TEST_COUNT\` | \`backend/test/security.test.mjs\` |
| Firestore Rules Emulator Tests | \`$RULES_TEST_COUNT\` | \`firestore.test.js\` |
| Swallowed \`catch (_)\` Count (\`app/src/main\`) | \`$SWALLOWED_COUNT\` | \`.ci/swallowed-baseline.txt\` |
EOF

if [ "${1:-}" = "--check" ]; then
  if [ ! -f "$OUT" ] || ! diff -u "$OUT" "$TMP" >/dev/null 2>&1; then
    echo "FAIL: $OUT is stale or missing. Run: bash scripts/gen-facts.sh"
    exit 1
  fi
  echo "ok: $OUT is up to date"
else
  mkdir -p "$(dirname "$OUT")"
  cp "$TMP" "$OUT"
  echo "Updated $OUT"
fi
