package com.ayra.ai.app.security

import android.content.Context
import org.json.JSONObject
import java.io.ByteArrayInputStream
import java.io.ByteArrayOutputStream
import java.io.DataInputStream
import java.io.DataOutputStream
import java.io.File
import java.io.InputStream
import java.nio.charset.StandardCharsets
import java.security.SecureRandom
import java.util.UUID
import javax.crypto.Cipher
import javax.crypto.spec.GCMParameterSpec
import javax.crypto.spec.SecretKeySpec

data class EncryptedVaultEntry(
    val fileId: String,
    val folder: String,
    val originalName: String,
    val mimeType: String,
    val vaultFile: File,
    val encryptedSizeBytes: Long,
    val createdMs: Long
)

/**
 * Envelope-Encrypted Private Data Vault for AYRA AI files (`filesDir/encrypted_vault`).
 *
 * Cryptographic Architecture:
 * - Each stored file receives an independent 256-bit Data Encryption Key (DEK) generated by [SecureRandom].
 * - File bytes are encrypted using AES-256-GCM with a unique 96-bit IV and bound AAD:
 *   `"$folder|$fileId|$originalName|$createdMs|v1"`.
 * - Each file's DEK is wrapped using [AyraKeyManager.ALIAS_FILE_KEK] with AAD `"dek|$folder|$fileId|v1"`.
 * - Binary container format: `AYRAVLT1` (8 bytes) + int32 header length + UTF-8 JSON header + ciphertext+GCM tag.
 */
object EncryptedVaultStorage {

    private const val MAGIC = "AYRAVLT1"
    private const val VAULT_ROOT_DIR = "encrypted_vault"
    private const val SHARE_CACHE_SUBDIR = "exports"
    private const val GCM_TAG_BITS = 128
    private const val GCM_IV_BYTES = 12

    private val secureRandom = SecureRandom()

    fun isVaultFile(file: File?): Boolean {
        if (file == null || !file.exists() || !file.isFile || file.length() < 12) return false
        return runCatching {
            file.inputStream().use { ins ->
                val magic = ByteArray(8)
                ins.read(magic) == 8 && String(magic, StandardCharsets.US_ASCII) == MAGIC
            }
        }.getOrDefault(false)
    }

    fun getVaultRoot(context: Context): File =
        File(context.filesDir, VAULT_ROOT_DIR).apply { if (!exists()) mkdirs() }

    /**
     * Encrypts [plaintextBytes] using a fresh per-file 256-bit DEK and writes an `.ayravlt` container.
     */
    fun storeEncryptedBytes(
        context: Context,
        folder: String,
        originalName: String,
        mimeType: String,
        plaintextBytes: ByteArray
    ): File {
        val safeFolder = folder.replace(Regex("[^a-zA-Z0-9_-]"), "_").ifBlank { "vault_misc" }
        val safeOriginal = originalName.replace(Regex("[^a-zA-Z0-9._-]"), "_").ifBlank { "file.bin" }
        val fileId = UUID.randomUUID().toString().replace("-", "").take(16)
        val createdMs = System.currentTimeMillis()

        val dekBytes = ByteArray(32).also { secureRandom.nextBytes(it) }
        val fileIv = ByteArray(GCM_IV_BYTES).also { secureRandom.nextBytes(it) }
        val fileAad = "$safeFolder|$fileId|$safeOriginal|$createdMs|v1".toByteArray(StandardCharsets.UTF_8)

        val ciphertext = try {
            val dekSpec = SecretKeySpec(dekBytes, "AES")
            val cipher = Cipher.getInstance("AES/GCM/NoPadding")
            cipher.init(Cipher.ENCRYPT_MODE, dekSpec, GCMParameterSpec(GCM_TAG_BITS, fileIv))
            cipher.updateAAD(fileAad)
            cipher.doFinal(plaintextBytes)
        } finally {
            // Wrap DEK before zeroing raw DEK bytes
        }

        val wrappedDek = try {
            AyraKeyManager.encryptAesGcm(
                context = context,
                baseAlias = AyraKeyManager.ALIAS_FILE_KEK,
                plaintext = dekBytes,
                aad = "dek|$safeFolder|$fileId|v1".toByteArray(StandardCharsets.UTF_8)
            )
        } finally {
            dekBytes.fill(0)
        }

        val headerJson = JSONObject().apply {
            put("v", 1)
            put("fileId", fileId)
            put("folder", safeFolder)
            put("originalName", safeOriginal)
            put("mimeType", mimeType)
            put("createdMs", createdMs)
            put("kekGen", wrappedDek.keyGeneration)
            put("fileIv", AyraKeyManager.encodeB64(fileIv))
            put("dekIv", AyraKeyManager.encodeB64(wrappedDek.iv))
            put("wrappedDek", AyraKeyManager.encodeB64(wrappedDek.ciphertext))
        }.toString().toByteArray(StandardCharsets.UTF_8)

        val targetDir = File(getVaultRoot(context), safeFolder).apply { if (!exists()) mkdirs() }
        val destFile = File(targetDir, "${safeOriginal}.$fileId.ayravlt")

        DataOutputStream(destFile.outputStream().buffered()).use { dos ->
            dos.write(MAGIC.toByteArray(StandardCharsets.US_ASCII))
            dos.writeInt(headerJson.size)
            dos.write(headerJson)
            dos.write(ciphertext)
            dos.flush()
        }

        SecurityAuditLogger.log(
            context = context,
            category = SecurityAuditCategory.VAULT_STORAGE,
            severity = SecurityAuditSeverity.INFO,
            message = "Encrypted artifact saved to vault [$safeFolder/${safeOriginal.take(24)}] (${ciphertext.size}B)"
        )
        return destFile
    }

    /**
     * Encrypts an existing file into the vault and optionally securely wipes the source file.
     */
    fun storeEncryptedFile(
        context: Context,
        folder: String,
        sourceFile: File,
        mimeType: String = "application/octet-stream",
        wipeSource: Boolean = true
    ): File {
        val bytes = sourceFile.readBytes()
        val vaultFile = storeEncryptedBytes(
            context = context,
            folder = folder,
            originalName = sourceFile.name,
            mimeType = mimeType,
            plaintextBytes = bytes
        )
        bytes.fill(0)
        if (wipeSource) {
            AndroidHardeningHelper.secureWipeFile(sourceFile)
        }
        return vaultFile
    }

    fun readMetadata(vaultFile: File): EncryptedVaultEntry {
        DataInputStream(vaultFile.inputStream().buffered()).use { dis ->
            val magic = ByteArray(8)
            dis.readFully(magic)
            require(String(magic, StandardCharsets.US_ASCII) == MAGIC) { "Invalid AYRAVLT container magic" }
            val headerLen = dis.readInt()
            require(headerLen in 16..65536) { "Invalid vault header size: $headerLen" }
            val headerBytes = ByteArray(headerLen)
            dis.readFully(headerBytes)
            val obj = JSONObject(String(headerBytes, StandardCharsets.UTF_8))
            return EncryptedVaultEntry(
                fileId = obj.getString("fileId"),
                folder = obj.getString("folder"),
                originalName = obj.getString("originalName"),
                mimeType = obj.optString("mimeType", "application/octet-stream"),
                vaultFile = vaultFile,
                encryptedSizeBytes = vaultFile.length(),
                createdMs = obj.getLong("createdMs")
            )
        }
    }

    fun decryptVaultFileBytes(context: Context?, vaultFile: File): ByteArray {
        DataInputStream(vaultFile.inputStream().buffered()).use { dis ->
            val magic = ByteArray(8)
            dis.readFully(magic)
            require(String(magic, StandardCharsets.US_ASCII) == MAGIC) { "Not an AYRAVLT encrypted container" }
            val headerLen = dis.readInt()
            require(headerLen in 16..65536) { "Corrupt vault header length" }
            val headerBytes = ByteArray(headerLen)
            dis.readFully(headerBytes)
            val obj = JSONObject(String(headerBytes, StandardCharsets.UTF_8))

            val fileId = obj.getString("fileId")
            val folder = obj.getString("folder")
            val originalName = obj.getString("originalName")
            val createdMs = obj.getLong("createdMs")
            val kekGen = obj.optInt("kekGen", 1)
            val fileIv = AyraKeyManager.decodeB64(obj.getString("fileIv"))
            val dekIv = AyraKeyManager.decodeB64(obj.getString("dekIv"))
            val wrappedDek = AyraKeyManager.decodeB64(obj.getString("wrappedDek"))

            val ciphertext = ByteArrayOutputStream().use { baos ->
                dis.copyTo(baos)
                baos.toByteArray()
            }

            val dekBytes = AyraKeyManager.decryptAesGcm(
                context = context,
                baseAlias = AyraKeyManager.ALIAS_FILE_KEK,
                iv = dekIv,
                ciphertext = wrappedDek,
                aad = "dek|$folder|$fileId|v1".toByteArray(StandardCharsets.UTF_8),
                keyGeneration = kekGen
            )

            return try {
                val dekSpec = SecretKeySpec(dekBytes, "AES")
                val cipher = Cipher.getInstance("AES/GCM/NoPadding")
                cipher.init(Cipher.DECRYPT_MODE, dekSpec, GCMParameterSpec(GCM_TAG_BITS, fileIv))
                cipher.updateAAD("$folder|$fileId|$originalName|$createdMs|v1".toByteArray(StandardCharsets.UTF_8))
                cipher.doFinal(ciphertext)
            } finally {
                dekBytes.fill(0)
            }
        }
    }

    fun openDecryptedStream(context: Context?, file: File): InputStream {
        return if (isVaultFile(file)) {
            ByteArrayInputStream(decryptVaultFileBytes(context, file))
        } else {
            file.inputStream()
        }
    }

    /**
     * Decrypts an encrypted vault artifact into `cacheDir/exports/` ONLY on explicit user share/open,
     * allowing Android FileProvider / PdfRenderer / Document viewer intents without keeping
     * persistent plaintext copies in filesDir. Call [wipeTempShareFiles] on lock/background.
     */
    fun materializeTempDecryptedFile(context: Context, file: File): File {
        if (!isVaultFile(file)) return file
        val meta = readMetadata(file)
        val plain = decryptVaultFileBytes(context, file)
        val shareDir = File(context.cacheDir, SHARE_CACHE_SUBDIR).apply { if (!exists()) mkdirs() }
        val outFile = File(shareDir, meta.originalName)
        outFile.writeBytes(plain)
        plain.fill(0)
        return outFile
    }

    fun wipeTempShareFiles(context: Context) {
        val shareDir = File(context.cacheDir, SHARE_CACHE_SUBDIR)
        if (shareDir.exists()) {
            AndroidHardeningHelper.secureWipeFile(shareDir)
        }
    }

    fun listVaultArtifacts(context: Context): List<EncryptedVaultEntry> {
        val root = getVaultRoot(context)
        val entries = mutableListOf<EncryptedVaultEntry>()
        root.walkTopDown()
            .filter { it.isFile && it.name.endsWith(".ayravlt") }
            .forEach { file ->
                runCatching { readMetadata(file) }.onSuccess { entries.add(it) }
            }
        return entries.sortedByDescending { it.createdMs }
    }

    fun wipeAllVaultFiles(context: Context): Int {
        var count = 0
        val root = getVaultRoot(context)
        if (root.exists()) {
            root.walkBottomUp().forEach { f ->
                if (f != root) {
                    if (f.isFile) count++
                    AndroidHardeningHelper.secureWipeFile(f)
                }
            }
        }
        wipeTempShareFiles(context)
        return count
    }
}
